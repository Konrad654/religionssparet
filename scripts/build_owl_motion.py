"""Build 30 fps animation atlases from the existing generated owl key poses.

Requires Pillow, numpy and opencv-python. Run from the repository root.
Two-way optical flow warps both poses before blending in premultiplied alpha.
This preserves transparent edges and creates moving in-betweens, rather than
repeating six drawings faster. All clips finish in the same neutral pose.
"""
from functools import lru_cache
from pathlib import Path
import math

import cv2
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
FPS, SIZE, COLS = 30, 256, 8
SOURCE = np.asarray(Image.open(ROOT / "owl-motion.webp").convert("RGBA"))
POSES = [SOURCE[y*SIZE:(y+1)*SIZE, x*SIZE:(x+1)*SIZE].copy()
         for y in range(4) for x in range(6)]
GRID_X, GRID_Y = np.meshgrid(np.arange(SIZE, dtype=np.float32),
                           np.arange(SIZE, dtype=np.float32))


def premultiply(frame):
    pixels = frame.astype(np.float32) / 255
    pixels[..., :3] *= pixels[..., 3:4]
    return pixels


def rgba(pixels):
    alpha = np.clip(pixels[..., 3:4], 0, 1)
    rgb = pixels[..., :3] / np.maximum(alpha, 1/255)
    return np.round(np.concatenate([np.clip(rgb, 0, 1), alpha], axis=2)*255).astype(np.uint8)


def gray(frame):
    pixels = premultiply(frame)
    # Opaque white outside the character lets the flow track its silhouette.
    composite = (pixels[..., :3] + 1 - pixels[..., 3:4]) * 255
    return cv2.cvtColor(composite.astype(np.uint8), cv2.COLOR_RGB2GRAY)


@lru_cache(maxsize=None)
def flows(a, b):
    algorithm = cv2.DISOpticalFlow_create(cv2.DISOPTICAL_FLOW_PRESET_MEDIUM)
    forward = algorithm.calc(gray(POSES[a]), gray(POSES[b]), None)
    reverse = algorithm.calc(gray(POSES[b]), gray(POSES[a]), None)
    return forward, reverse


def interpolate(a, b, fraction):
    if a == b or fraction <= 0:
        return POSES[a].copy()
    if fraction >= 1:
        return POSES[b].copy()
    fraction = np.float32(fraction)
    forward, reverse = flows(a, b)
    left = cv2.remap(premultiply(POSES[a]), GRID_X - fraction*forward[..., 0],
                     GRID_Y - fraction*forward[..., 1], cv2.INTER_LINEAR,
                     borderMode=cv2.BORDER_CONSTANT)
    right = cv2.remap(premultiply(POSES[b]), GRID_X - (1-fraction)*reverse[..., 0],
                      GRID_Y - (1-fraction)*reverse[..., 1], cv2.INTER_LINEAR,
                      borderMode=cv2.BORDER_CONSTANT)
    return rgba(left*(1-fraction) + right*fraction)


def sample(keys, t):
    for (start, a), (end, b) in zip(keys, keys[1:]):
        if t <= end:
            weight = np.clip((t-start)/(end-start), 0, 1)
            weight = weight*weight*(3-2*weight)
            return interpolate(a, b, weight)
    return POSES[keys[-1][1]].copy()


CLIPS = {
    "idle": (90, [(0,0),(.62,0),(.66,1),(.70,2),(.73,3),(.77,4),(.82,5),(1,0)]),
    "wave": (48, [(0,0),(.06,6),(.17,7),(.29,8),(.40,9),(.51,10),
                   (.62,9),(.73,10),(.84,7),(.94,11),(1,0)]),
    "celebrate": (60, [(0,0),(.06,12),(.15,13),(.24,14),(.32,15),(.42,16),
                        (.50,17),(.59,13),(.68,14),(.76,15),(.84,16),(.91,12),(1,0)]),
    "think": (72, [(0,0),(.08,18),(.22,19),(.38,20),(.54,21),(.69,22),
                    (.80,23),(.90,19),(1,0)]),
}


def build():
    css = ["/* Generated by scripts/build_owl_motion.py. Each frame lasts 1/30 s. */",
           "@media(prefers-reduced-motion:no-preference){"]
    for mood, (count, keys) in CLIPS.items():
        rows = math.ceil(count/COLS)
        atlas = Image.new("RGBA", (COLS*SIZE, rows*SIZE))
        for i in range(count):
            t = i/(count-1)
            frame = sample(keys, t)
            if mood == "idle":
                # Small breathing movement, continuous across the loop boundary.
                shift = -1.2 * (1-math.cos(t*2*math.pi))
                pixels = cv2.warpAffine(premultiply(frame),
                    np.float32([[1,0,0],[0,1,shift]]), (SIZE,SIZE),
                    flags=cv2.INTER_LINEAR, borderMode=cv2.BORDER_CONSTANT)
                frame = rgba(pixels)
            atlas.paste(Image.fromarray(frame), ((i%COLS)*SIZE, (i//COLS)*SIZE))
        path = ROOT / f"owl-{mood}-30.webp"
        atlas.save(path, "WEBP", quality=86, method=6, exact=True)
        name = f"owl-{mood}-30"
        iterations = "infinite" if mood == "idle" else "1 forwards"
        css.append(f'.owl-sprite[data-owl-ready="true"][data-mood="{mood}"]{{background-image:url("{path.name}");'
                   f'background-size:{COLS*100}% {rows*100}%;background-position:0 0;'
                   f'animation:{name} {count/FPS:g}s steps(1,end) {iterations}}}')
        css.append(f"@keyframes {name}{{")
        for i in range(count):
            x, y = (i%COLS)*100/(COLS-1), (i//COLS)*100/(rows-1)
            css.append(f"{i*100/count:.6f}%{{background-position:{x:.6f}% {y:.6f}%}}")
        css.append(f"100%{{background-position:{x:.6f}% {y:.6f}%}}}}")
        print(f"{mood}: {count} frames, {count/FPS:g} s, {FPS} fps, {path.stat().st_size:,} bytes")
    css.append("}")
    (ROOT / "owl-motion.css").write_text("\n".join(css) + "\n")


if __name__ == "__main__":
    build()
